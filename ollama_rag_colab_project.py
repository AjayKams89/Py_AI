import gc
import os
import shutil
import time
import traceback
import uuid
import gradio as gr
from langchain_community.document_loaders import PyPDFLoader
from langchain_text_splitters import RecursiveCharacterTextSplitter
from langchain_ollama import OllamaEmbeddings, ChatOllama
from langchain_chroma import Chroma
from langchain_core.prompts import ChatPromptTemplate

DB_PREFIX = "./chroma_rag_db_"
vectorstore = None
current_db_dir = None
current_doc_names = []


def process_pdfs(pdf_files, chunk_size, chunk_overlap):
    global vectorstore, current_db_dir, current_doc_names

    if not pdf_files:
        return "Please upload one or more PDF files first.", "Active Documents: None"

    files_list = pdf_files if isinstance(pdf_files, list) else [pdf_files]

    try:
        previous_dir = current_db_dir
        vectorstore = None
        gc.collect()
        time.sleep(0.2)

        if previous_dir and os.path.exists(previous_dir):
            shutil.rmtree(previous_dir, ignore_errors=True)

        splitter = RecursiveCharacterTextSplitter(
            chunk_size=int(chunk_size),
            chunk_overlap=int(chunk_overlap),
        )

        all_chunks = []
        total_pages = 0
        indexed_names = []
        skipped_names = []

        for file_obj in files_list:
            file_path = file_obj.name if hasattr(file_obj, "name") else str(file_obj)
            base_name = os.path.basename(file_path)

            loader = PyPDFLoader(file_path)
            docs = loader.load()
            if not docs:
                skipped_names.append(base_name)
                continue

            total_pages += len(docs)
            indexed_names.append(base_name)

            for doc in docs:
                doc.metadata["source_file"] = base_name

            all_chunks.extend(splitter.split_documents(docs))

        if not all_chunks:
            return (
                "No extractable text found in any uploaded PDF (files may be scanned images).",
                "Active Documents: None",
            )

        run_dir = f"{DB_PREFIX}{uuid.uuid4().hex[:8]}"
        embeddings = OllamaEmbeddings(model="nomic-embed-text")
        vectorstore = Chroma.from_documents(
            documents=all_chunks,
            embedding=embeddings,
            persist_directory=run_dir,
        )
        current_db_dir = run_dir
        current_doc_names = indexed_names

        status_lines = [
            f"Indexed {len(indexed_names)} PDF(s): {', '.join(indexed_names)}",
            f"Total pages: {total_pages} | Total chunks: {len(all_chunks)}",
        ]
        if skipped_names:
            status_lines.append(f"Skipped (no text): {', '.join(skipped_names)}")

        return "\n".join(status_lines), f"Active Documents: {len(indexed_names)} file(s)"
    except Exception as e:
        traceback.print_exc()
        return f"Error processing PDFs: {str(e)}", "Active Documents: Error"


def ask_question(message, history, top_k, temperature):
    global vectorstore
    history = list(history or [])

    if not message or not message.strip():
        return "", history

    if vectorstore is None:
        history.append({"role": "user", "content": message})
        history.append({
            "role": "assistant",
            "content": "Please upload and index one or more PDFs in the left panel first.",
        })
        return "", history

    try:
        retriever = vectorstore.as_retriever(search_kwargs={"k": int(top_k)})
        retrieved_docs = retriever.invoke(message)

        context_parts = []
        sources = set()
        for doc in retrieved_docs:
            file_name = doc.metadata.get("source_file", "Unknown PDF")
            page_num = doc.metadata.get("page", 0) + 1
            sources.add(f"{file_name} (Page {page_num})")
            context_parts.append(f"[{file_name} - Page {page_num}]: {doc.page_content}")

        context_text = "\n\n---\n\n".join(context_parts)

        prompt = ChatPromptTemplate.from_template(
            """You are a helpful AI document assistant. Answer the user's question using ONLY the provided context.
If the answer is not present in the context, state clearly: "I couldn't find that information in the uploaded documents."
Keep your answer clear, structured, and accurate.

Context:
{context}

Question: {question}
Answer:"""
        )

        llm = ChatOllama(model="llama3.2", temperature=float(temperature))
        chain = prompt | llm
        response = chain.invoke({"context": context_text, "question": message})

        sorted_sources = ", ".join(sorted(sources)) if sources else "None"
        final_answer = f"{response.content}\n\n---\n**Sources:** {sorted_sources}"

        history.append({"role": "user", "content": message})
        history.append({"role": "assistant", "content": final_answer})
        return "", history
    except Exception as e:
        traceback.print_exc()
        history.append({"role": "user", "content": message})
        history.append({"role": "assistant", "content": f"Error generating answer: {str(e)}"})
        return "", history


with gr.Blocks(title="Local RAG Studio") as demo:
    gr.Markdown(
        """
        # Local RAG Document Studio
        Powered by **Ollama (`llama3.2` + `nomic-embed-text`)**, **LangChain**, and **ChromaDB**.
        """
    )

    with gr.Row():
        with gr.Column(scale=1):
            gr.Markdown("### 1. Knowledge Base")
            doc_badge = gr.Textbox(value="Active Documents: None", label="Status", interactive=False)
            pdf_input = gr.File(
                label="Upload PDFs",
                file_types=[".pdf"],
                file_count="multiple",
            )

            with gr.Accordion("RAG Parameters", open=False):
                chunk_size_slider = gr.Slider(300, 1500, value=800, step=100, label="Chunk Size (chars)")
                chunk_overlap_slider = gr.Slider(0, 400, value=150, step=50, label="Chunk Overlap (chars)")
                top_k_slider = gr.Slider(1, 12, value=6, step=1, label="Retrieved Chunks (Top-K)")
                temp_slider = gr.Slider(0.0, 1.0, value=0.2, step=0.1, label="LLM Temperature")

            index_btn = gr.Button("Build Vector Index", variant="primary")
            ingest_output = gr.Textbox(label="Indexing Log", lines=4, interactive=False)

        with gr.Column(scale=2):
            gr.Markdown("### 2. Ask Your Documents")
            chatbot = gr.Chatbot(height=460, label="RAG Assistant")
            with gr.Row():
                msg_box = gr.Textbox(
                    placeholder="Ask a question about your uploaded PDFs...",
                    show_label=False,
                    scale=4,
                )
                send_btn = gr.Button("Send", variant="primary", scale=1)
            clear_btn = gr.Button("Clear Chat", variant="secondary")

    index_btn.click(
        fn=process_pdfs,
        inputs=[pdf_input, chunk_size_slider, chunk_overlap_slider],
        outputs=[ingest_output, doc_badge],
    )

    msg_box.submit(
        fn=ask_question,
        inputs=[msg_box, chatbot, top_k_slider, temp_slider],
        outputs=[msg_box, chatbot],
    )

    send_btn.click(
        fn=ask_question,
        inputs=[msg_box, chatbot, top_k_slider, temp_slider],
        outputs=[msg_box, chatbot],
    )

    clear_btn.click(lambda: [], None, chatbot, queue=False)

demo.launch(share=True, debug=False)